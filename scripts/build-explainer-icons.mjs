function parseIconNode(source) {
  const m = /const __iconNode = (\[[\s\S]*?\]);\n/.exec(source);
  if (!m) return null;
  // The node is plain JS object/array literals with string values.
  return Function(`"use strict"; return (${m[1]});`)();
}

const icons = {};
const missing = [];
for (const name of [...new Set(WANTED)]) {
  const file = path.join(ICON_DIR, `${name}.js`);
  if (!fs.existsSync(file)) {
    missing.push(name);
    continue;
  }
  const node = parseIconNode(fs.readFileSync(file, "utf8"));
  if (!node) {
    missing.push(name);
    continue;
  }
  icons[name] = node.map(([tag, attrs]) => {
    const { key: _key, ...rest } = attrs;
    return [tag, rest];
  });
}

const names = Object.keys(icons).sort();
const banner = "/* Generated by scripts/build-explainer-icons.mjs from lucide-react (ISC). Do not edit. */\n";
fs.writeFileSync(
  path.join("video-templates", "explainer", "icons.js"),
  `${banner}window.EXPLAINER_ICONS = ${JSON.stringify(icons)};\n`
);
fs.writeFileSync(
  path.join("src", "lib", "explainer-icons.ts"),
  `${banner}export const EXPLAINER_ICON_NAMES = ${JSON.stringify(names, null, 2)} as const;\n\nexport type ExplainerIconName = (typeof EXPLAINER_ICON_NAMES)[number];\n\nconst SET = new Set<string>(EXPLAINER_ICON_NAMES);\n\nexport function isExplainerIcon(name: unknown): name is ExplainerIconName {\n  return typeof name === "string" && SET.has(name);\n}\n`
);
console.log(`${names.length} icons written. Missing: ${missing.join(", ") || "none"}`);
